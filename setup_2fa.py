from getpass import getpass

from src.user_database import (
    initialize_database,
    get_user,
    enable_two_factor,
)

from src.two_factor_auth import (
    generate_secret,
    verify_totp,
)


def main():
    print("=" * 55)
    print("ESKMS TWO-FACTOR AUTHENTICATION SETUP")
    print("=" * 55)

    initialize_database()

    username = input("\nEnter ESKMS username: ").strip()

    user = get_user(username)

    if user is None:
        print("\nERROR: User does not exist.")
        return

    if not user["is_active"]:
        print("\nERROR: User account is inactive.")
        return

    if user["two_factor_enabled"]:
        print("\n2FA is already enabled for this user.")
        return

    print(f"\nSetting up 2FA for: {username}")
    print(f"Role: {user['role']}")

    secret = generate_secret()

    print("\nYour TOTP secret is:")
    print(secret)

    print("\nAdd this secret to your authenticator app.")
    print("Then enter the 6-digit code generated by the app.")

    code = getpass("\nEnter current TOTP code: ").strip()

    if not verify_totp(secret, code):
        print("\nERROR: Invalid TOTP code.")
        print("2FA has NOT been enabled.")
        return

    enable_two_factor(username, secret)

    print("\n2FA enabled successfully!")
    print(f"Username: {username}")
    print(f"Role: {user['role']}")


if __name__ == "__main__":
    main()